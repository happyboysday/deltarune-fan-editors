/** 檢查（或測試用）：每個命名空間三語鍵集合是否一致；回傳不一致的描述陣列。 */
export function findKeyMismatches(table = STRINGS, locales = LOCALE_IDS) {
  const problems = [];
  for (const [ns, bundle] of Object.entries(table)) {
    const base = Object.keys(bundle[locales[0]] || {}).sort();
    const baseSet = new Set(base);
    for (const loc of locales.slice(1)) {
      const keys = Object.keys(bundle[loc] || {});
      const keySet = new Set(keys);
      for (const k of baseSet) if (!keySet.has(k)) problems.push(`${ns}/${loc} 缺少鍵：${k}`);
      for (const k of keySet) if (!baseSet.has(k)) problems.push(`${ns}/${loc} 多出鍵：${k}`);
    }
    for (const loc of locales) {
      for (const [k, v] of Object.entries(bundle[loc] || {})) {
        if (typeof v !== 'string' || v === '') problems.push(`${ns}/${loc} 空字串：${k}`);
      }
    }
  }
  return problems;
}

