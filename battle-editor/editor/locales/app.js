export default strings;

export const NAMESPACES = ['app', 'toolbar', 'preview', 'fileops'];

/** 把本檔字串註冊進 editor/i18n.js（可重複呼叫） */
export function registerAppStrings(i18n) {
  const reg = i18n && typeof i18n.registerStrings === 'function' ? i18n.registerStrings : null;
  if (!reg) return false;
  for (const [locale, nsMap] of Object.entries(strings)) {
    for (const ns of NAMESPACES) reg(ns, { [locale]: nsMap[ns] });
  }
  return true;
}

