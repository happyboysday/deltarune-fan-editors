export const NAMESPACES = ['encapp', 'enctoolbar', 'encpreview', 'encfileops'];

/** 把本檔字串註冊進 editor/i18n.js（可重複呼叫） */
export function registerEncounterAppStrings(i18nModule) {
  const mod = i18nModule || i18n;
  const reg = mod && typeof mod.registerStrings === 'function' ? mod.registerStrings : null;
  if (!reg) return false;
  for (const [locale, nsMap] of Object.entries(strings)) {
    for (const ns of NAMESPACES) reg(ns, { [locale]: nsMap[ns] });
  }
  return true;
}

// 副作用註冊：只要 import 本檔就能用 t('encapp.brand') 等
